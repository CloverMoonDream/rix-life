// 保留的两道闸门是**有意互补**的：
//   ① 这里（启发式）：抓"长得像凭据赋值"的文本；
//   ② KNOWN_AGENT_TOKENS 精确名单（bridge.js）：抓**已知的**会话令牌原文，
